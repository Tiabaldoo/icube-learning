namespace SpriteKind {
    export const ТипВрага = SpriteKind.create()
    export const ТипФиниша = SpriteKind.create()
    export const ТипКлюча = SpriteKind.create()
}

function начатьПопытку () {
    tiles.placeOnRandomTile(Игрок, sprites.dungeon.collectibleInsignia)
    if (Уровень == 2) {
        ЕстьКлюч = false
        tiles.placeOnRandomTile(Ключ, sprites.dungeon.floorLight2)
        Ключ.setFlag(SpriteFlag.Invisible, false)
        Ключ.setFlag(SpriteFlag.Ghost, false)
        tiles.setTileAt(Дверь, sprites.dungeon.doorClosedNorth)
        tiles.setWallAt(Дверь, true)
    }
}

function загрузитьУровень () {
    if (Уровень == 1) {
        tiles.setCurrentTilemap(tilemap`level1`)
        Ключ.setFlag(SpriteFlag.Invisible, true)
        Ключ.setFlag(SpriteFlag.Ghost, true)
    } else {
        tiles.setCurrentTilemap(tilemap`level2`)
        Дверь = tiles.getTilesByType(sprites.dungeon.doorClosedNorth)[0]
    }
    tiles.placeOnRandomTile(Враг, sprites.dungeon.floorLight3)
    tiles.placeOnRandomTile(Финиш, sprites.dungeon.chestClosed)
    начатьПопытку()
}

scene.onHitWall(SpriteKind.Player, function (sprite, location) {
    if (Уровень == 2 && ЕстьКлюч && tiles.tileAtLocationEquals(location, sprites.dungeon.doorClosedNorth)) {
        tiles.setWallAt(location, false)
        tiles.setTileAt(location, sprites.dungeon.floorLight0)
    }
})
sprites.onOverlap(SpriteKind.Player, SpriteKind.ТипКлюча, function (sprite, otherSprite) {
    ЕстьКлюч = true
    Ключ.setFlag(SpriteFlag.Invisible, true)
    Ключ.setFlag(SpriteFlag.Ghost, true)
})
sprites.onOverlap(SpriteKind.Player, SpriteKind.ТипФиниша, function (sprite, otherSprite) {
    if (Уровень == 1) {
        Уровень = 2
    } else {
        game.over(true)
    }
})
sprites.onOverlap(SpriteKind.Player, SpriteKind.ТипВрага, function (sprite, otherSprite) {
    tiles.placeOnRandomTile(Игрок, sprites.dungeon.collectibleInsignia)
})
